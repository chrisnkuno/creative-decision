temps = st.floats(0.2, 5.0)


# B1 ----------------------------------------------------------------------------------------
@given(simplex(), temps, temps)
def test_b1_tempering_is_a_group_action(p: Vec, t1: float, t2: float) -> None:
    assert close(temper(p, 1.0), p)
    assert close(temper(temper(p, t1), t2), temper(p, t1 * t2))


@given(simplex(), temps)
def test_b1_tempering_preserves_the_ranking(p: Vec, t: float) -> None:
    q = temper(p, t)
    for i in range(p.size):
        for j in range(p.size):
            if p[i] > p[j] + 1e-9:
                assert q[i] >= q[j]


@given(simplex())
def test_b1_infinite_temperature_is_ignorance(p: Vec) -> None:
    assert close(temper(p, 1e9), uniform(p.size), 1e-6)


@given(temps)
def test_b1_a_coin_flip_stays_a_coin_flip(t: float) -> None:
    cal = Calibrator(temperature={"noul": t, "score": 1, "choice": 1})
    assert abs(cal.noul(0.5) - 0.5) < 1e-12


# B2 ----------------------------------------------------------------------------------------
@settings(max_examples=40)
@given(st.lists(simplex(3), min_size=3, max_size=20), st.data())
def test_b2_calibration_nll_is_convex_in_beta(dists: list[Vec], data: st.DataObject) -> None:
    labels = [data.draw(st.integers(0, 2)) for _ in dists]
    betas = np.linspace(0.1, 6, 60)
    f = np.array([nll(float(b), dists, labels, 0.02) for b in betas])
    second = f[:-2] - 2 * f[1:-1] + f[2:]
    assert np.all(second >= -1e-7 * max(1.0, float(np.abs(f).max())))


def test_b2_fit_recovers_a_known_miscalibration() -> None:
    """Data generated by a judge that is overconfident by T* = 2 → fit finds T ≈ 2."""
    rng = np.random.default_rng(0)
    t_star, dists, labels = 2.0, [], []
    for _ in range(3000):
        truth = rng.dirichlet(np.ones(4))
        reported = power(t_star, truth)  # overconfident: sharpened by T*
        dists.append(reported)
        labels.append(int(rng.choice(4, p=truth)))
    cal = Calibrator(smoothing={"score": 0.0, "choice": 0.0, "noul": 0.0})
    assert abs(cal.fit("choice", dists, labels) - t_star) < 0.15


# B3 ----------------------------------------------------------------------------------------
@given(same_size_simplices(3), st.permutations([0, 1, 2]))
def test_b3_pool_is_symmetric_in_judges(ps: list[Vec], perm: list[int]) -> None:
    w = [0.2, 0.3, 0.5]
    assert close(log_pool(ps, w), log_pool([ps[i] for i in perm], [w[i] for i in perm]))


@given(simplex(), st.lists(st.floats(0.05, 1), min_size=1, max_size=5))
def test_b3_pool_is_unanimous_when_weights_sum_to_one(p: Vec, w: list[float]) -> None:
    w = [x / sum(w) for x in w]
    assert close(log_pool([p] * len(w), w), p)


@given(same_size_simplices(4), st.lists(st.floats(0.05, 2), min_size=3, max_size=3))
def test_b3_pool_commutes_with_bayesian_update(ps: list[Vec], w: list[float]) -> None:
    """pool(ℓ ⊕ p_j) = (Σw) ⊙ ℓ ⊕ pool(p_j); external Bayesianity is the case Σw = 1."""
    *beliefs, lik = ps
    lhs = log_pool([perturb(lik, p) for p in beliefs], w)
    rhs = perturb(power(sum(w), lik), log_pool(beliefs, w))
    assert close(lhs, rhs, 1e-8)
    w1 = [x / sum(w) for x in w]
    assert close(
        log_pool([perturb(lik, p) for p in beliefs], w1), perturb(lik, log_pool(beliefs, w1))
    )


def test_b3_a_confident_judge_vetoes_a_label() -> None:
    sure_no = np.array([0.5, 0.5 - 1e-9, 1e-9])
    keen = np.array([0.1, 0.1, 0.8])
    assert log_pool([sure_no, keen], [0.5, 0.5])[2] < 1e-3


# B4 ----------------------------------------------------------------------------------------
def biased_answers(p: Vec, bias: Vec, orbit: list[list[int]]) -> list[Vec]:
    """A judge with multiplicative position bias b: shows present(p) ⊕ b, decoded back."""
    return [relabel(perturb(present(p, order), bias), order) for order in orbit]


@given(st.integers(2, 7), st.data())
def test_b4_cyclic_orbit_removes_any_position_bias_exactly(n: int, data: st.DataObject) -> None:
    p, bias = data.draw(simplex(n)), data.draw(simplex(n))
    assert close(orbit_mean(biased_answers(p, bias, cyclic_orbit(n)), 0.0), p, 1e-8)


@given(st.integers(2, 7), st.data())
def test_b4_reversal_removes_exactly_the_odd_part(n: int, data: st.DataObject) -> None:
    p, bias = data.draw(simplex(n)), data.draw(simplex(n))
    got = orbit_mean(biased_answers(p, bias, reversal_orbit(n)), 0.0)
    c = clr(bias)
    even = (c + c[::-1]) / 2
    assert close(clr(got), clr(p) + even, 1e-8)
    odd_only = clr_inv((c - c[::-1]) / 2)
    assert close(orbit_mean(biased_answers(p, odd_only, reversal_orbit(n)), 0.0), p, 1e-8)


@given(st.integers(2, 7), st.data())
def test_b4_an_unbiased_judge_is_a_fixed_point(n: int, data: st.DataObject) -> None:
    p = data.draw(simplex(n))
    for orbit in (cyclic_orbit(n), reversal_orbit(n)):
        assert close(orbit_mean(biased_answers(p, uniform(n), orbit), 0.0), p)


# B5 ----------------------------------------------------------------------------------------
@given(st.lists(st.floats(0, 50), min_size=2, max_size=5), st.floats(-20, 20), st.floats(0.5, 3))
def test_b5_hedge_weights(losses: list[float], shift: float, total: float) -> None:
    names = [f"j{i}" for i in range(len(losses))]
    a = JudgeWeights(names, total=total, loss=dict(zip(names, losses, strict=True)))
    b = JudgeWeights(names, total=total, loss={n: x + shift for n, x in a.loss.items()})
    wa = a.weights()
    assert close(wa, b.weights())
    assert abs(sum(wa) - total) < 1e-9
    for i in range(len(losses)):
        for j in range(len(losses)):
            if losses[i] < losses[j]:
                assert wa[i] >= wa[j]


def test_b5_hedge_learns_which_judge_is_right() -> None:
    w = JudgeWeights(["good", "bad"])
    for _ in range(20):
        w.observe("good", np.array([0.1, 0.9]), 1)
        w.observe("bad", np.array([0.9, 0.1]), 1)
    good, bad = w.weights()
    assert good > 0.99 > bad
